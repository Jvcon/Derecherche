import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import YAML from "yaml";

const root = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const catalogDir = path.join(root, "catalog");
const generatedDir = path.join(root, "generated");

const TYPES = `// Generated by packages/data/scripts/build.mjs. Do not edit by hand.

export type EngineStatus = "active" | "deprecated" | "broken";

export interface CategoryChild {
  id: string;
  name: string;
  order: number;
  aliases?: string[];
  icon?: string;
  description?: string;
}

export interface Category extends CategoryChild {
  children?: CategoryChild[];
}

export interface Provider {
  id: string;
  name: string;
  homepage?: string;
  icon?: string;
  regions?: string[];
  notes?: string;
}

export interface Engine {
  id: string;
  providerId: string;
  name: string;
  category: string;
  tags?: string[];
  url: string;
  icon?: string;
  triggers?: string[];
  regions?: string[];
  languages?: string[];
  order?: number;
  status: EngineStatus;
  replacedBy?: string;
  legacyId?: string;
  notes?: string;
}

export interface Site {
  id: string;
  name: string;
  hosts: string[];
  pathPattern?: string;
  paramMatches?: Record<string, string>;
  priority?: number;
  urlParams?: string[];
  selectors?: {
    query?: string[];
  };
  defaultCategory: string;
  capabilities?: Array<"url" | "dom" | "html">;
  mount?: {
    anchor?: string;
    container?: string;
    placement?: "below" | "above" | "floating";
    offset?: number;
  };
  notes?: string;
}

export interface IconRef {
  symbol: string;
  slug: string;
  title: string;
}

export interface IconManifest {
  schemaVersion: 1;
  catalogVersion: string;
  sprite: string | null;
  source: string;
  sourceUrl: string;
  license: string;
  icons: Record<string, IconRef>;
  missing: string[];
}

export interface Catalog {
  schemaVersion: 1;
  catalogVersion: string;
  categories: Category[];
  providers: Provider[];
  engines: Engine[];
  sites: Site[];
}

declare const catalog: Catalog;
export default catalog;

export const schemaVersion: 1;
export const catalogVersion: string;
export const categories: Category[];
export const providers: Provider[];
export const engines: Engine[];
export const sites: Site[];
export const icons: IconManifest;
`;

const INDEX = `// Generated by packages/data/scripts/build.mjs. Do not edit by hand.
import catalog from "./catalog.json" with { type: "json" };
import icons from "./icons.json" with { type: "json" };

export default catalog;
export const { schemaVersion, catalogVersion, categories, providers, engines, sites } = catalog;
export { icons };
`;

async function readYaml(file) {
  return YAML.parse(await fs.readFile(file, "utf8"));
}

async function listYaml(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  return entries
    .filter((entry) => entry.isFile() && /\.ya?ml$/i.test(entry.name))
    .map((entry) => path.join(dir, entry.name))
    .sort();
}

function stableJson(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function assertSingleVersion(label, files, values) {
  const unique = [...new Set(values)];
  if (unique.length !== 1) {
    throw new Error(
      `${label} versions do not match across ${files.join(", ")}: ${unique.join(", ")}`
    );
  }
  return unique[0];
}

async function main() {
  const categoriesFile = path.join(catalogDir, "categories.yaml");
  const providersFile = path.join(catalogDir, "providers.yaml");
  const categoriesDoc = await readYaml(categoriesFile);
  const providersDoc = await readYaml(providersFile);

  const engineFiles = await listYaml(path.join(catalogDir, "engines"));
  const engineDocs = [];
  for (const file of engineFiles) {
    engineDocs.push({ file, doc: await readYaml(file) });
  }

  const siteFiles = await listYaml(path.join(catalogDir, "sites"));
  const sites = [];
  for (const file of siteFiles) {
    sites.push(await readYaml(file));
  }

  const catalogVersion = assertSingleVersion(
    "catalog",
    [categoriesFile, providersFile, ...engineDocs.map(({ file }) => file)],
    [
      categoriesDoc.catalogVersion,
      providersDoc.catalogVersion,
      ...engineDocs.map(({ doc }) => doc.catalogVersion),
    ]
  );

  const schemaVersion = assertSingleVersion(
    "schema",
    [categoriesFile, providersFile, ...engineDocs.map(({ file }) => file)],
    [
      categoriesDoc.schemaVersion,
      providersDoc.schemaVersion,
      ...engineDocs.map(({ doc }) => doc.schemaVersion),
    ]
  );

  const engines = engineDocs.flatMap(({ doc }) =>
    doc.engines.map((engine) => ({
      ...engine,
      status: engine.status ?? "active",
    }))
  );

  const catalog = {
    schemaVersion,
    catalogVersion,
    categories: categoriesDoc.categories,
    providers: providersDoc.providers,
    engines,
    sites,
  };

  await fs.mkdir(generatedDir, { recursive: true });
  await Promise.all([
    fs.writeFile(path.join(generatedDir, "catalog.json"), stableJson(catalog)),
    fs.writeFile(path.join(generatedDir, "catalog.d.ts"), TYPES),
    fs.writeFile(path.join(generatedDir, "index.d.ts"), TYPES),
    fs.writeFile(path.join(generatedDir, "index.js"), INDEX),
  ]);

  console.log("Catalog build passed.");
  console.log(`  catalogVersion: ${catalogVersion}`);
  console.log(`  categories:     ${catalog.categories.length}`);
  console.log(`  providers:      ${catalog.providers.length}`);
  console.log(`  engines:        ${catalog.engines.length}`);
  console.log(`  sites:          ${catalog.sites.length}`);
}

main().catch((error) => {
  console.error(error.message ?? error);
  process.exit(1);
});
